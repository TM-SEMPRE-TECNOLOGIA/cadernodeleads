    function saveScorecardToLead() {
      const lead = currentCockpitLead;
      if (!lead) {
        closeScorecardModal();
        return;
      }

      const checks = document.querySelectorAll('.score-check');
      const checkedArr = [];
      let count = 0;
      checks.forEach(chk => {
        checkedArr.push(chk.checked);
        if (chk.checked) count++;
      });

      const notesEl = document.getElementById('scorecard-notes');
      const notesVal = notesEl ? notesEl.value.trim() : '';

      if (!lead.cockpit) lead.cockpit = {};
      lead.cockpit.lastScorecard = {
        score: count,
        checked: checkedArr,
        notes: notesVal,
        savedAt: new Date().toISOString()
      };

      // Adiciona ao histórico do lead
      if (!lead.history) lead.history = [];
      lead.history.push({
        type: 'scorecard',
        date: new Date().toLocaleDateString('pt-BR'),
        text: `Scorecard de Call: ${count}/10 pontos. Nota de coaching: "${notesVal || 'Sem anotações'}"`
      });

      saveState();
      renderLeadsNotebook();
      closeScorecardModal();
      showToast(`📊 Scorecard de ${count}/10 salvo no dossiê de ${lead.name}!`);
    }

