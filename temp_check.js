    function askHermesAI(query, hint, onFallback) {
      const leadId = document.getElementById('hermes-lead-context').value || '';
      appendHermesMessage('user', query);

      // indicador "escrevendo" com animação + bloqueio de duplo envio
      appendHermesTyping();
      setHermesBusy(true);
      if (hermesAbortCtrl) hermesAbortCtrl.abort();
      hermesAbortCtrl = new AbortController();

      const body = { message: query };
      if (leadId) body.leadId = leadId;
      if (hint) body.system = hint;

      // timeout de segurança: 35s (o relay grátis pode demorar)
      const timeoutId = setTimeout(() => hermesAbortCtrl && hermesAbortCtrl.abort(), 35000);

      fetch('/api/chat', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(body),
        signal: hermesAbortCtrl.signal
      })
      .then(res => res.json().then(d => ({ ok: res.ok, d })))
      .then(({ ok, d }) => {
        clearTimeout(timeoutId);
        clearHermesTyping();
        if (ok && d.reply) {
          appendHermesMessage('assistant', renderAIHTML(d.reply) + `<div class="text-[9px] text-zinc-400 mt-1.5 opacity-70">⚡ IA grátis ativa (${escHtml(d.model || 'nemotron')})</div>`);
        } else {
          throw new Error(d.error || 'Sem resposta da IA');
        }
      })
      .catch(err => {
        clearTimeout(timeoutId);
        console.error('Hermes AI falhou:', err);
        clearHermesTyping();
        const timedOut = err && err.name === 'AbortError';
        const reason = timedOut
          ? 'A IA demorou mais de 35s para responder (o modelo grátis pode estar congestionado).'
          : 'Não consegui contatar a IA agora. Verifique se o servidor local (porta 3333) está no ar.';
        const retryBtn = onFallback ? '' :
          `<div class="mt-2"><button onclick="retryLastHermesQuery()" class="bg-amber-600 hover:bg-amber-700 text-white px-3 py-1 rounded text-[11px] font-bold">🔄 Tentar novamente</button></div>`;
        appendHermesMessage('assistant', `<span class="text-rose-600 dark:text-rose-400 font-bold">⚠️ Erro na IA:</span> ${reason}${retryBtn}`);
        if (onFallback) {
          appendHermesMessage('assistant', `<span class="text-zinc-400 text-[11px]">Usando resposta local como alternativa:</span>`);
          onFallback();
        }
      });
    }

    let lastHermesQuery = '';
    function retryLastHermesQuery() {
      const q = lastHermesQuery;
      if (!q) return;
      // remove mensagens de erro anteriores do assistente antes de tentar de novo
      const chatBody = document.getElementById('hermes-chat-body');
      const msgs = chatBody.querySelectorAll(':scope > div');
      for (let i = msgs.length - 1; i >= 0; i--) {
        const t = msgs[i].innerText || '';
        if (t.includes('Erro na IA') || t.includes('Usando resposta local')) msgs[i].remove();
      }
      askHermesAI(q);
    }

    function escHtml(t) {
      return String(t || '')
        .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;');
    }

    function renderAIHTML(text) {
      // Escapa e aplica formatação leve: **negrito**, linhas e listas "• "
      const esc = escHtml(text);
      let html = esc
        .replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>')
        .replace(/`([^`]+)`/g, '<code class="bg-zinc-200 dark:bg-zinc-800 px-1 rounded text-[10px]">$1</code>');
      const lines = html.split('\n');
      const out = [];
      for (const line of lines) {
        const t = line.trim();
        if (!t) continue;
        if (/^[-*•]\s+/.test(t)) {
          out.push(`<div class="flex gap-1.5 ml-1"><span>•</span><span>${t.replace(/^[-*•]\s+/, '')}</span></div>`);
        } else if (/^\d+[.)]\s+/.test(t)) {
          out.push(`<div class="flex gap-1.5 ml-1"><span>${t.match(/^\d+[.)]/)[0]}</span><span>${t.replace(/^\d+[.)]\s+/, '')}</span></div>`);
        } else {
          out.push(`<div>${t}</div>`);
        }
      }
      return out.join('');
    }

