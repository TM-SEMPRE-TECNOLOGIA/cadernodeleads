    function getNextPilar(current) {
      const order = ['prospeccao', 'qualificacao', 'negociacao', 'fechamento', 'pos_venda'];
      const idx = order.indexOf(current);
      if (idx !== -1 && idx < order.length - 1) return order[idx + 1];
      return null;
    }

    function advancePilar(leadId) {
      const lead = appData.leads.find(l => l.id === leadId);
      if (!lead) return;
      const next = getNextPilar(lead.status);
      if (next) {
        lead.status = next;
        saveState();
        showToast(`Lead avançado para: ${next.toUpperCase()}! 🚀`);
      }
    }

    // Drag & Drop Handlers
    function handleDragStart(e, leadId) {
      draggedLeadId = leadId;
      e.dataTransfer.setData('text/plain', leadId);
      e.currentTarget.classList.add('dragging');
    }

    function handleDragEnd(e) {
      e.currentTarget.classList.remove('dragging');
      document.querySelectorAll('.kanban-dropzone').forEach(el => el.classList.remove('drag-over'));
      draggedLeadId = null;
    }

    function handleDragOver(e) {
      e.preventDefault();
      const dropzone = e.currentTarget;
      if (!dropzone.classList.contains('drag-over')) {
        dropzone.classList.add('drag-over');
      }
    }

    function handleDragLeave(e) {
      e.currentTarget.classList.remove('drag-over');
    }

    function handleDrop(e, targetPilar) {
      e.preventDefault();
      e.currentTarget.classList.remove('drag-over');
      const leadId = e.dataTransfer.getData('text/plain') || draggedLeadId;
      if (!leadId) return;

      const lead = appData.leads.find(l => l.id === leadId);
      if (lead && lead.status !== targetPilar) {
        lead.status = targetPilar;
        saveState();
        showToast(`Lead movido para: ${targetPilar.toUpperCase()}! ✨`);
        if (targetPilar === 'pos_venda' && window.confetti) {
          confetti({ particleCount: 80, spread: 60, origin: { y: 0.6 } });
        }
      }
    }

